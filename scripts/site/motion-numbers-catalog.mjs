// scripts/site/motion-numbers-catalog.mjs: regenerate the motion NUMBER tables in engine-doctrine/RULES from the
// engine, so a stagger value, a default ease or an exit-speed number can't drift between doc and code.
//
//   node scripts/site/motion-numbers-catalog.mjs            write the generated blocks
//   node scripts/site/motion-numbers-catalog.mjs --check    fail if any block is stale (make check GATE=generated-check)
//
// Same contract as scripts/site/vocab-catalog.mjs: the NUMBERS come from the registry, not from a
// hand-typed copy, so the doc cannot state a value the engine no longer has. Unlike vocab-catalog this
// writes only a fenced block inside each doc (between GENERATED markers), because these are prose rule
// docs with hand-written judgment around one small table, not a pure catalogue page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_MOTION, exitRatioFromMotion } from '../../core/motion/motion.js';
import { DURATION } from '../../core/registry/vocab.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const CHECK = process.argv.includes('--check');
const START = '<!-- GENERATED:motion-numbers -->';
const END = '<!-- /GENERATED:motion-numbers -->';

function block(lines) {
  return [START, '> GENERATED by `scripts/site/motion-numbers-catalog.mjs` (`make regen`) from '
    + '`core/motion/motion.js` and `core/registry/vocab.js`. Do not edit by hand.', '', ...lines, END].join('\n');
}

const easeDirection = block([
  '| motion number | value | source |',
  '|---|---|---|',
  `| default ease | \`${DEFAULT_MOTION.easing}\` | \`DEFAULT_MOTION.easing\` (core/motion/motion.js) |`,
  `| default exitRatio (durationScale 1) | ${exitRatioFromMotion(1)} | \`exitRatioFromMotion(1)\` |`,
  `| exitRatio band | ${exitRatioFromMotion(0.8)}–${exitRatioFromMotion(1.05)}, clamped 0.3–0.7 | \`exitRatioFromMotion\` over the authored \`durationScale\` band |`,
]);

const staggerTotal = block([
  '| motion number | value | source |',
  '|---|---|---|',
  `| default per-unit stagger | ${DEFAULT_MOTION.stagger}s | \`DEFAULT_MOTION.stagger\` (core/motion/motion.js), read as \`kit.M.stagger\` |`,
]);

const speedBands = block([
  '| word | seconds | source |',
  '|---|---|---|',
  ...Object.entries(DURATION).map(([w, s]) => `| \`${w}\` | ${s}s | \`DURATION.${w}\` (core/registry/vocab.js) |`),
  '',
  'Full word list with the "when": `engine-doctrine/CRAFT/VOCABULARY.md#duration`.',
]);

const TARGETS = [
  ['engine-doctrine/RULES/ease-direction.md', easeDirection],
  ['engine-doctrine/RULES/stagger-total.md', staggerTotal],
  ['engine-doctrine/RULES/speed-bands.md', speedBands],
];

let stale = false;
for (const [rel, content] of TARGETS) {
  const dest = path.join(root, rel);
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  const re = new RegExp(`${START}[\\s\\S]*?${END}`);
  if (!re.test(cur)) {
    console.error(`✗ ${rel} has no ${START} ... ${END} block to fill. Add one where the numbers belong.`);
    process.exit(1);
  }
  const next = cur.replace(re, content);
  if (CHECK) {
    if (next !== cur) { console.error(`✗ ${rel} is stale, run \`make regen\`.`); stale = true; }
    continue;
  }
  if (next !== cur) fs.writeFileSync(dest, next);
}
if (CHECK) {
  if (stale) process.exit(1);
  console.log('✓ engine-doctrine/RULES motion-number blocks are in sync with the engine');
} else {
  console.log('✓ wrote motion-number blocks into engine-doctrine/RULES/ease-direction.md, stagger-total.md, speed-bands.md');
}
